import { NextRequest } from "next/server";
import { chatRequestSchema } from "@/lib/schemas";

// --- Lightweight imports: no heavy deps (Anthropic, Voyage, Supabase).
// Static here so they are resolved once at module load, not on every request.
// This removes 100-300 ms of cold-start dynamic-import cost for rejected
// requests (rate-limit, validation, injection) that never need the AI stack.
import { checkRateLimit, normalizeIpForRateLimit } from "@/lib/rate-limit";
import { withRouteContext } from "@/lib/request-validation";
import { getClientIp } from "@/lib/request-utils";
import {
  detectInjectionAttempt,
  detectPromptLeakage,
  sanitizeInput,
} from "@/lib/chat-safety";
import { getLocalizedSafetyRedirect } from "@/lib/chat-config";
import { logger } from "@/lib/logger";
import { buildEnrichedChatMessage, buildRateLimitHeaders } from "@/lib/chat-route-utils";
import {
  CHAT_STREAM_STAGE_TIMEOUTS_MS,
  CHAT_STREAM_RESPONSE_TOTAL_CAP_MS,
  createBoundedGenerationTimer,
  isChatStreamStageTimeout,
  withChatStreamStageTiming,
} from "@/lib/chat-stream-timeouts";
import { encodeSseEvent } from "@/types/sse";

// PE-H5 (#808): explicit ceiling, replacing Vercel's implicit default, kept
// strictly above the worst-case internal budget (embedding 12s + search 5s +
// featureFlag 2s + CHAT_STREAM_RESPONSE_TOTAL_CAP_MS 90s = 109s) so the
// internal timeouts below — not this platform ceiling — always fire first.
// Vercel's currently documented default (Fluid Compute, on by default) is
// 300s for every plan tier, so 120s tightens that ceiling rather than
// raising it. Assumes Fluid Compute is active for this project; reconfirm
// against Settings > Functions > Function Max Duration if not.
export const maxDuration = 120;

function rateLimitedResponse(headers: Record<string, string>): Response {
  return new Response(
    JSON.stringify({ error: "Too many requests. Please try again later." }),
    { status: 429, headers: { "Content-Type": "application/json", ...headers } }
  );
}

function isAbortError(error: unknown): boolean {
  return (
    (error instanceof DOMException && error.name === "AbortError") ||
    (error instanceof Error && error.name === "AbortError")
  );
}

/**
 * Streaming chat endpoint using Server-Sent Events (SSE)
 *
 * Returns a stream of text chunks as they're generated by Claude.
 * Final event includes any relevant images.
 */
export async function POST(request: NextRequest) {
  // DO-M1 (#619): bind X-Request-ID into the request context so handler logs
  // carry request_id.
  return withRouteContext(request, () => handlePost(request));
}

// BE-H1: stricter shared-bucket rate limit for requests without a trusted Vercel IP
// header. All such clients share one bucket with a tighter cap (3 req/60s) to prevent
// the "unknown" key from being used as a bypass. On Vercel production, all real
// requests carry x-vercel-forwarded-for, so this only fires in unusual conditions.
const UNTRUSTED_RATE_LIMIT = { windowMs: 60_000, maxRequests: 3, maxEntries: 1 };

async function handlePost(request: NextRequest) {
  let releaseRequestAbort: (() => void) | undefined;
  let streamOwnsCleanup = false;
  try {
    // Rate limiting
    const ip = getClientIp(request);
    if (ip === "unknown") {
      logger.warn("[CHAT_STREAM_UNTRUSTED_IP]", {
        path: "/api/chat/stream",
        reason: "no_vercel_forwarded_for",
      });
    }
    let rateLimit: Awaited<ReturnType<typeof checkRateLimit>>;
    try {
      // PE-M3 (#811): checkRateLimit's own catch only fires when the Upstash
      // call REJECTS. A degraded-but-not-failing Upstash region instead just
      // hangs, and this is the first I/O on the chat path — ahead of every
      // other stage timeout — so an unbounded hang here is invisible in the
      // stage-timing logs used to diagnose the pipeline. Bound it the same way
      // as the other stages.
      // BE-L5 (#798): normalize IPv6 to its /64 prefix before it becomes the
      // bucket key — otherwise a residential /64 allocation gives one
      // subscriber 2^64 distinct buckets (trivially rotated via IPv6 privacy
      // extensions), making the limit effectively unenforceable. IPv4 and
      // the "untrusted" sentinel pass through unchanged.
      rateLimit = await withChatStreamStageTiming(
        "rateLimit",
        checkRateLimit(
          ip === "unknown" ? "untrusted" : normalizeIpForRateLimit(ip),
          ip === "unknown" ? UNTRUSTED_RATE_LIMIT : undefined
        )
      );
    } catch (rateLimitErr) {
      // Only the stage TIMEOUT is handled here — checkRateLimit() itself never
      // rejects (it has its own internal try/catch, see rate-limit.ts), so any
      // other rejection is a genuinely unexpected bug and should fall through
      // to the outer catch's generic 500, not be silently swallowed here.
      if (!isChatStreamStageTimeout(rateLimitErr)) {
        throw rateLimitErr;
      }
      // Fail CLOSED on timeout — same direction as checkRateLimit's own
      // production error path. Letting the request through here would turn a
      // slow Upstash into a rate-limit bypass.
      logger.warn("[CHAT_STREAM_RATE_LIMIT_TIMEOUT]", {
        stage: rateLimitErr.stage,
      });
      return rateLimitedResponse({ "Retry-After": "60" });
    }

    if (!rateLimit.allowed) {
      return rateLimitedResponse(buildRateLimitHeaders(rateLimit, true));
    }

    // Input validation — single Zod parse path (BE-L3 #524).
    const body = await request.json().catch(() => null);
    const zodResult = chatRequestSchema.safeParse(body);
    if (!zodResult.success) {
      return new Response(
        JSON.stringify({ error: "Invalid request", details: zodResult.error.flatten() }),
        { status: 400, headers: { "Content-Type": "application/json" } }
      );
    }

    const { message, context, messageIndex, locale = 'es' } = zodResult.data;

    // Security checks
    if (message && detectInjectionAttempt(message)) {
      // Return a non-streaming response with generic redirect
      return new Response(
        JSON.stringify({
          message: await getLocalizedSafetyRedirect(locale),
          flagged: true,
        }),
        {
          headers: { "Content-Type": "application/json" },
        }
      );
    }

    const cleanMessage = sanitizeInput(message);

    const streamAbortController = new AbortController();
    const handleRequestAbort = () => {
      streamAbortController.abort();
    };

    if (request.signal.aborted) {
      handleRequestAbort();
    } else {
      request.signal.addEventListener("abort", handleRequestAbort, { once: true });
    }

    releaseRequestAbort = () => request.signal.removeEventListener("abort", handleRequestAbort);

    // --- Heavy imports: deferred until after all validation passes ---
    // VERIFIED 2026-04-23 on Next.js 16.2.4: keep these imports deferred.
    // They still avoid loading the AI stack for rejected requests, and the repo's
    // Turbopack/Anthropic regression remains documented in
    // docs/engineering/turbopack-fix.md. Do not convert back to static imports
    // without re-running that reproduction with live upstream credentials.
    const [
      { streamChatResponse, extractSourcesFromChunks },
      { retrieveChatContext },
      { isFeatureFlagEnabled },
    ] = await Promise.all([
      import("@/lib/claude"),
      import("@/lib/retrieve-chat-context"),
      import("@/lib/feature-flags-server"),
    ]);

    // PE-H3: start the feature-flag lookup concurrently with embedding generation.
    // The flag is independent of the retrieval pipeline, so firing it now lets it
    // resolve (typically a fast cached Supabase read) while the embedding round-trip
    // is in flight.  We suppress unhandled rejections here; the promise is awaited
    // below once retrieval is complete.
    const asturianEnabledPromise = isFeatureFlagEnabled("asturianu_touches");
    void asturianEnabledPromise.catch(() => {});

    let chunks: Awaited<ReturnType<typeof retrieveChatContext>>["chunks"] = [];
    let images: Awaited<ReturnType<typeof retrieveChatContext>>["images"] = [];
    try {
      ({ chunks, images } = await retrieveChatContext(cleanMessage, 3, { signal: streamAbortController.signal }));
    } catch (searchErr) {
      releaseRequestAbort();
      const encoder = new TextEncoder();
      const errorStream = new ReadableStream({
        start(controller) {
          if (!request.signal.aborted) {
            logger.warn("[CHAT_STREAM_SEARCH_UNAVAILABLE]", {
              error: searchErr,
              stage: isChatStreamStageTimeout(searchErr) ? searchErr.stage : undefined,
            });
            controller.enqueue(encoder.encode(encodeSseEvent({ type: "error", message: "search_unavailable" })));
          }
          controller.close();
        },
      });
      return new Response(errorStream, {
        headers: { "Content-Type": "text/event-stream", "Cache-Control": "no-cache" },
      });
    }

    // Enrich message with context
    const enrichedMessage = buildEnrichedChatMessage(cleanMessage, context);

    let asturianEnabled = false;
    try {
      asturianEnabled = await withChatStreamStageTiming("featureFlag", asturianEnabledPromise) && locale === 'ast';
    } catch (flagErr) {
      logger.warn("[CHAT_STREAM_FEATURE_FLAG_FALLBACK]", { error: flagErr });
    }

    // Create a readable stream for SSE
    const encoder = new TextEncoder();

    let ended = false;
    let generationTimer: ReturnType<typeof createBoundedGenerationTimer> | undefined;
    let removeGenerationAbort: (() => void) | undefined;
    const cleanup = () => {
      generationTimer?.dispose();
      removeGenerationAbort?.();
      releaseRequestAbort?.();
    };
    const stream = new ReadableStream({
      async start(controller) {
        const send = (event: Parameters<typeof encodeSseEvent>[0]) => {
          if (ended || request.signal.aborted) return;
          controller.enqueue(encoder.encode(encodeSseEvent(event)));
        };
        const end = () => {
          if (ended) return;
          ended = true;
          cleanup();
          try { controller.close(); } catch { /* Client cancellation already closed it. */ }
        };
        const onAbort = () => {
          if (!ended) logger.warn("[CHAT_STREAM_ABORTED]", { reason: "client_disconnect" });
          end();
        };
        streamAbortController.signal.addEventListener("abort", onAbort, { once: true });
        removeGenerationAbort = () => streamAbortController.signal.removeEventListener("abort", onAbort);
        if (streamAbortController.signal.aborted) { end(); return; }
        generationTimer = createBoundedGenerationTimer({
          idleMs: CHAT_STREAM_STAGE_TIMEOUTS_MS.response,
          totalMs: CHAT_STREAM_RESPONSE_TOTAL_CAP_MS,
          onTimeout(reason, timeoutMs) {
            logger.warn(reason === "total_duration_cap" ? "[CHAT_STREAM_RESPONSE_TOTAL_CAP]" : "[CHAT_STREAM_RESPONSE_TIMEOUT]", { timeoutMs, reason });
            send({ type: "error", message: "response_timeout" });
            end();
            streamAbortController.abort();
          },
        });
        let accumulatedText = "";
        try {
          for await (const chunk of streamChatResponse(
            enrichedMessage, chunks, asturianEnabled, messageIndex, images,
            { signal: streamAbortController.signal, locale }
          )) {
            if (ended || streamAbortController.signal.aborted) break;
            generationTimer.resetIdle();
            // Check the entire accumulated output before sending any new text.
            accumulatedText += chunk;
            if (detectPromptLeakage(accumulatedText)) {
              logger.error("[CHAT_STREAM_SECURITY]", {
                timestamp: new Date().toISOString(), outputPreview: accumulatedText.slice(0, 200),
              });
              send({ type: "error", message: "output_filtered" });
              end();
              streamAbortController.abort();
              break;
            }
            send({ type: "text", content: chunk });
          }
          if (!ended && !streamAbortController.signal.aborted) {
            send({ type: "done", images, sources: extractSourcesFromChunks(chunks) });
          }
        } catch (error) {
          if (ended) {
            // The timeout, disconnect or filter already ended the stream.
          } else if (isAbortError(error) || streamAbortController.signal.aborted) {
            logger.warn("[CHAT_STREAM_ABORTED]", { reason: "client_disconnect" });
          } else {
            const err = error instanceof Error ? error : new Error(String(error));
            logger.error("[CHAT_STREAM_FAILURE]", { error: err.message, type: err.constructor?.name ?? "Error" });
            send({ type: "error", message: "Error generating response" });
          }
        } finally { end(); }
      },
      cancel() {
        if (!ended) logger.warn("[CHAT_STREAM_ABORTED]", { reason: "client_disconnect" });
        ended = true;
        cleanup();
        streamAbortController.abort();
      },
    });
    streamOwnsCleanup = true;

    return new Response(stream, {
      headers: {
        "Content-Type": "text/event-stream",
        "Cache-Control": "no-cache",
        Connection: "keep-alive",
        ...buildRateLimitHeaders(rateLimit),
      },
    });
  } catch (error) {
    logger.error("[CHAT_STREAM_API_ERROR]", { error });
    return new Response(
      JSON.stringify({ error: "Internal server error" }),
      {
        status: 500,
        headers: { "Content-Type": "application/json" },
      }
    );
  } finally {
    if (!streamOwnsCleanup) releaseRequestAbort?.();
  }
}
