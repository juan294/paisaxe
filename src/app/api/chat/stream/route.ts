import { NextRequest } from "next/server";
import { chatRequestSchema } from "@/lib/schemas";

// --- Lightweight imports: no heavy deps (Anthropic, Voyage, Supabase).
// Static here so they are resolved once at module load, not on every request.
// This removes 100-300 ms of cold-start dynamic-import cost for rejected
// requests (rate-limit, validation, injection) that never need the AI stack.
import { validateChatRequest } from "@/lib/validation";
import { checkRateLimit } from "@/lib/rate-limit";
import { getClientIp } from "@/lib/request-utils";
import {
  detectInjectionAttempt,
  sanitizeInput,
  MAX_INPUT_LENGTH,
} from "@/lib/chat-safety";
import { GENERIC_REDIRECT_RESPONSE } from "@/lib/chat-config";
import { logger } from "@/lib/logger";
import { buildEnrichedChatMessage, buildRateLimitHeaders } from "@/lib/chat-route-utils";
import { CHAT_STREAM_STAGE_TIMEOUTS_MS, type ChatStreamStage } from "@/lib/chat-stream-timeouts";
import { encodeSseEvent } from "@/types/sse";

class ChatStreamStageTimeoutError extends Error {
  constructor(
    readonly stage: ChatStreamStage,
    readonly timeoutMs: number
  ) {
    super(`${stage} timed out after ${timeoutMs}ms`);
    this.name = "ChatStreamStageTimeoutError";
  }
}

function isAbortError(error: unknown): boolean {
  return (
    (error instanceof DOMException && error.name === "AbortError") ||
    (error instanceof Error && error.name === "AbortError")
  );
}

function isChatStreamStageTimeout(error: unknown): error is ChatStreamStageTimeoutError {
  return error instanceof ChatStreamStageTimeoutError;
}

async function withStageTiming<T>(
  stage: ChatStreamStage,
  promise: Promise<T>
): Promise<T> {
  const startedAt = Date.now();
  const timeoutMs = CHAT_STREAM_STAGE_TIMEOUTS_MS[stage];
  let timer: ReturnType<typeof setTimeout> | undefined;
  let timedOut = false;

  const timeoutPromise = new Promise<never>((_, reject) => {
    timer = setTimeout(() => {
      timedOut = true;
      reject(new ChatStreamStageTimeoutError(stage, timeoutMs));
    }, timeoutMs);
  });

  try {
    return await Promise.race([promise, timeoutPromise]);
  } catch (error) {
    if (isChatStreamStageTimeout(error)) {
      logger.warn("[CHAT_STREAM_STAGE_TIMEOUT]", {
        stage,
        timeoutMs,
      });
    }
    throw error;
  } finally {
    if (timer !== undefined) clearTimeout(timer);
    logger.info("[CHAT_STREAM_STAGE_TIMING]", {
      stage,
      durationMs: Date.now() - startedAt,
      timeoutMs,
      timedOut,
    });
  }
}

/**
 * Streaming chat endpoint using Server-Sent Events (SSE)
 *
 * Returns a stream of text chunks as they're generated by Claude.
 * Final event includes any relevant images.
 */
export async function POST(request: NextRequest) {
  try {
    // Rate limiting
    const ip = getClientIp(request);
    const rateLimit = await checkRateLimit(ip);

    if (!rateLimit.allowed) {
      return new Response(
        JSON.stringify({ error: "Too many requests. Please try again later." }),
        {
          status: 429,
          headers: {
            "Content-Type": "application/json",
            ...buildRateLimitHeaders(rateLimit, true),
          },
        }
      );
    }

    // Input validation — Zod runtime schema check first
    const body = await request.json().catch(() => null);
    const zodResult = chatRequestSchema.safeParse(body);
    if (!zodResult.success) {
      return new Response(
        JSON.stringify({ error: "Invalid request", details: zodResult.error.flatten() }),
        { status: 400, headers: { "Content-Type": "application/json" } }
      );
    }

    const validation = validateChatRequest(body);

    if (!validation.valid) {
      return new Response(JSON.stringify({ error: validation.error }), {
        status: 400,
        headers: { "Content-Type": "application/json" },
      });
    }

    const { sanitizedMessage: message, sanitizedContext: context, messageIndex } = validation;

    // Security checks
    if (message && message.length > MAX_INPUT_LENGTH) {
      return new Response(
        JSON.stringify({
          error: "Message too long",
        }),
        {
          status: 400,
          headers: { "Content-Type": "application/json" },
        }
      );
    }

    if (message && detectInjectionAttempt(message)) {
      // Return a non-streaming response with generic redirect
      return new Response(
        JSON.stringify({
          message: GENERIC_REDIRECT_RESPONSE,
          flagged: true,
        }),
        {
          headers: { "Content-Type": "application/json" },
        }
      );
    }

    const cleanMessage = sanitizeInput(message!);

    const streamAbortController = new AbortController();
    const handleRequestAbort = () => {
      streamAbortController.abort();
    };

    if (request.signal.aborted) {
      handleRequestAbort();
    } else {
      request.signal.addEventListener("abort", handleRequestAbort, { once: true });
    }

    // --- Heavy imports: deferred until after all validation passes ---
    // VERIFIED 2026-04-23 on Next.js 16.2.4: keep these imports deferred.
    // They still avoid loading the AI stack for rejected requests, and the repo's
    // Turbopack/Anthropic regression remains documented in
    // docs/engineering/turbopack-fix.md. Do not convert back to static imports
    // without re-running that reproduction with live upstream credentials.
    const [
      { streamChatResponse, extractSourcesFromChunks },
      { generateEmbedding },
      { search },
      { isFeatureFlagEnabled },
    ] = await Promise.all([
      import("@/lib/claude"),
      import("@/lib/embeddings"),
      import("@/lib/search"),
      import("@/lib/feature-flags-server"),
    ]);

    // PE-H3: start the feature-flag lookup concurrently with embedding generation.
    // The flag is independent of the retrieval pipeline, so firing it now lets it
    // resolve (typically a fast cached Supabase read) while the embedding round-trip
    // is in flight.  We suppress unhandled rejections here; the promise is awaited
    // below once retrieval is complete.
    const asturianEnabledPromise = isFeatureFlagEnabled("asturianu_touches");
    void asturianEnabledPromise.catch(() => {});

    // Generate embedding and search — fail gracefully on upstream errors.
    // search() depends on the embedding result, so these two steps remain serial.
    // The feature-flag promise above runs in parallel with both.
    let chunks: Awaited<ReturnType<typeof search>>["chunks"] = [];
    let images: Awaited<ReturnType<typeof search>>["images"] = [];
    try {
      const queryEmbedding = await withStageTiming(
        "embedding",
        generateEmbedding(cleanMessage)
      );
      ({ chunks, images } = await withStageTiming(
        "search",
        search(queryEmbedding, 3, cleanMessage)
      ));
    } catch (searchErr) {
      request.signal.removeEventListener("abort", handleRequestAbort);
      logger.warn("[CHAT_STREAM_SEARCH_UNAVAILABLE]", {
        error: searchErr,
        stage: isChatStreamStageTimeout(searchErr) ? searchErr.stage : undefined,
      });
      const encoder = new TextEncoder();
      const errorStream = new ReadableStream({
        start(controller) {
          controller.enqueue(
            encoder.encode(
              encodeSseEvent({
                type: "error",
                message: "search_unavailable",
              })
            )
          );
          controller.close();
        },
      });
      return new Response(errorStream, {
        headers: { "Content-Type": "text/event-stream", "Cache-Control": "no-cache" },
      });
    }

    // Enrich message with context
    const enrichedMessage = buildEnrichedChatMessage(cleanMessage, context);

    let asturianEnabled = false;
    try {
      asturianEnabled = await withStageTiming("featureFlag", asturianEnabledPromise);
    } catch (flagErr) {
      logger.warn("[CHAT_STREAM_FEATURE_FLAG_FALLBACK]", { error: flagErr });
    }

    // Create a readable stream for SSE
    const encoder = new TextEncoder();

    const stream = new ReadableStream({
      async start(controller) {
        try {
          // Stream text chunks
          for await (const chunk of streamChatResponse(
            enrichedMessage,
            chunks,
            asturianEnabled,
            messageIndex,
            images,
            { signal: streamAbortController.signal }
          )) {
            if (streamAbortController.signal.aborted) {
              break;
            }

            // Send text chunk as SSE event
            controller.enqueue(encoder.encode(
              encodeSseEvent({ type: "text", content: chunk })
            ));
          }

          // Send final event with images and sources
          if (!streamAbortController.signal.aborted) {
            const sources = extractSourcesFromChunks(chunks);
            controller.enqueue(encoder.encode(
              encodeSseEvent({
                type: "done",
                images,
                sources,
              })
            ));
          }

        } catch (error) {
          if (isAbortError(error) || streamAbortController.signal.aborted) {
            logger.warn("[CHAT_STREAM_ABORTED]", { reason: "client_disconnect" });
          } else {
            const err = error instanceof Error ? error : new Error(String(error));
            logger.error("[CHAT_STREAM_FAILURE]", {
              error: err.message,
              type: err.constructor?.name ?? "Error",
            });
            controller.enqueue(encoder.encode(
              encodeSseEvent({
                type: "error",
                message: "Error generating response",
              })
            ));
          }
        } finally {
          request.signal.removeEventListener("abort", handleRequestAbort);
          try {
            controller.close();
          } catch {
            // Ignore close races caused by upstream cancellation.
          }
        }
      },
      cancel() {
        streamAbortController.abort();
        request.signal.removeEventListener("abort", handleRequestAbort);
      },
    });

    return new Response(stream, {
      headers: {
        "Content-Type": "text/event-stream",
        "Cache-Control": "no-cache",
        Connection: "keep-alive",
        ...buildRateLimitHeaders(rateLimit),
      },
    });
  } catch (error) {
    logger.error("[CHAT_STREAM_API_ERROR]", { error });
    return new Response(
      JSON.stringify({ error: "Internal server error" }),
      {
        status: 500,
        headers: { "Content-Type": "application/json" },
      }
    );
  }
}
