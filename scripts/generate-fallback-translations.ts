import { writeFileSync } from "node:fs";
import fallback from "../content/fallback-stories.json";
import { STORY_TRANSLATIONS } from "../content/translations/story-translations";

// Keep the client fallback synchronous without shipping unrelated story text.
const translations = Object.fromEntries(fallback.stories.map(story => {
  const slug = story.slug ?? story.id;
  const translation = STORY_TRANSLATIONS[slug];
  if (!translation) throw new Error(`Missing fallback translations: ${slug}`);
  return [slug, translation];
}));

writeFileSync(new URL("../content/translations/fallback-story-translations.generated.ts", import.meta.url),
  `// Generated by: npx tsx scripts/generate-fallback-translations.ts
// Regenerate after changing fallback stories or their canonical translations.
import type { StoryLocale, StoryTranslation } from "@/types/immersive";

export const FALLBACK_STORY_TRANSLATIONS: Record<string, Partial<Record<StoryLocale, StoryTranslation>>> = ${JSON.stringify(translations, null, 2)};
`);
